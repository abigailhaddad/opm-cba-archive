"""Write data/SUMMARY.md: counts computed from data/cba_agreements.csv and the raw listing.

Run after build_table.py. Nothing here is typed in by hand.
"""

import csv
import glob
import json
import os
from collections import Counter

ROOT = os.environ.get("CBA_ROOT") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)

rows = list(csv.DictReader(open(P("data/cba_agreements.csv"))))
listing = sorted(glob.glob(P("data/raw/cba_listing_*.json")))[-1]
pulled = os.path.basename(listing).replace("cba_listing_", "").replace(".json", "")

listed = [r for r in rows if r.get("in_current_listing", "True") == "True"]
ok = [r for r in rows if r["download_status"] == "ok"]
text = Counter(r["text_status"] for r in rows)
flags = Counter(r["termination_flag"] for r in rows)
dod = Counter(r["termination_flag"] for r in rows if "Defense" in r["agencyName"])

labels = [
    ("confirmed", "Confirmed by an agency document or court record naming the agency and union"),
    ("confirmed_secondary", "Confirmed by press reports only"),
    ("confirmed_then_reinstated", "Terminated, then reinstated by a court"),
    ("inferred", 'Inferred: covered by an order ending "all" of an agency\'s agreements'),
    ("uncertain_injunction", "Possibly protected by a court injunction"),
    ("uncertain_certification", "Possibly in a DoD subdivision certified as exempt"),
    ("not_flagged_exempt_psf", "DoD police, firefighter or guard unit (carved out)"),
    ("not_flagged_no_source_found", "Covered by the orders, but no termination source found"),
    ("not_flagged_agency_not_named", "At agencies the orders don't cover"),
]
unknown = set(flags) - {k for k, _ in labels}
assert not unknown, f"unlabeled flags: {unknown}"

out = [
    "# Summary",
    "",
    f"Generated by `scripts/summary.py` from the listing pulled {pulled} (UTC). Don't edit by hand.",
    "",
    "## Archive",
    "",
    "| | Count |",
    "|---|---:|",
    f"| Agreements in OPM's listing | {len(listed):,} |",
    f"| Downloaded | {len(ok):,} |",
    f"| Not downloaded | {len(rows) - len(ok):,} |",
    f"| Unique files (SHA-256) | {len({r['sha256'] for r in ok}):,} |",
]
if len(rows) != len(listed):
    out.append(f"| No longer in OPM's listing, kept here | {len(rows) - len(listed):,} |")
for k, v in sorted(text.items(), key=lambda kv: -kv[1]):
    out.append(f"| Text status `{k or 'none'}` | {v:,} |")
out += [
    "",
    "## Termination flags",
    "",
    "| Flag | DoD | Other | Total |",
    "|---|---:|---:|---:|",
]
for k, label in labels:
    out.append(f"| {label} (`{k}`) | {dod[k]:,} | {flags[k] - dod[k]:,} | {flags[k]:,} |")
out.append(f"| **Total** | **{sum(dod.values()):,}** | **{len(rows) - sum(dod.values()):,}** | **{len(rows):,}** |")

open(P("data/SUMMARY.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
